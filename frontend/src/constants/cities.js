/** So sánh 2 city — trả về true nếu cùng thành phố */
export const isSameCity = (cityA, cityB) => {
  if (!cityA || !cityB) return false
  // Nếu cùng list thì so sánh thẳng (chính xác 100%)
  if (cityA === cityB) return true
  // Fallback normalize cho trường hợp nhập tay
  const normalize = (s) => s.toLowerCase()
    .replace(/\s+/g, ' ')
    .replace(/\s*\.\s*/g, '.')
    .replace(/^tp\.?\s*/i, '')
    .replace(/^tỉnh\s*/i, '')
    .replace(/thành phố\s*/i, '')
    .trim()
  return normalize(cityA) === normalize(cityB)
}